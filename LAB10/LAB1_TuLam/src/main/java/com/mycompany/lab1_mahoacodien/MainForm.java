    private void btnVigenereActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVigenereActionPerformed
       try {
    String plaintext = txtInput.getText().toUpperCase();
    String key = txtKey.getText().toUpperCase();
    
    if(key.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Vui lòng nhập khóa dạng CHỮ cho Vigenere!");
        return;
    }
    
    StringBuilder ciphertext = new StringBuilder();
    int keyIndex = 0;

    // Thuật toán mã hóa Vigenere đa đơn bảng
    for (int i = 0; i < plaintext.length(); i++) {
        char c = plaintext.charAt(i);
        if (Character.isLetter(c)) {
            int pIdx = c - 'A';
            int kIdx = key.charAt(keyIndex % key.length()) - 'A';
            char cipherChar = (char) (((pIdx + kIdx) % 26) + 'A');
            ciphertext.append(cipherChar);
            keyIndex++;
        } else {
            ciphertext.append(c);
        }
    }
    
    // Hiển thị kết quả ra ô Output
    txtOutput.setText(ciphertext.toString());
    
} catch (Exception ex) {
    javax.swing.JOptionPane.showMessageDialog(this, "Lỗi: " + ex.getMessage());
}

    }//GEN-LAST:event_btnVigenereActionPerformed

